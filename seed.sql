# Decisions made

1. **GroundStory remains the name.** The brand supports “the story of the ground” and “get in on the GroundStory.”
2. **Cloud-first, thin-client architecture.** The historical corpus will not live on the phone.
3. **Postgres/PostGIS before a separate graph database.** Relationship tables give us graph-like exploration without premature infrastructure.
4. **Pre-ingestion and caching before request-time web research.** The app should feel fast and consistent.
5. **Every claim keeps visible sources.** AI may summarize later, but it cannot become the authority.
6. **Launch measure:** five genuinely interesting nearby stories, not maximum record count.
7. **Pilot geography:** Logan and Sebastian Counties, Arkansas, after the basic pipeline is online.
